package main

import (
	"bytes"
	"fmt"
	"regexp"
	"strings"
	"time"
)

// Options controls a conversion.
type Options struct {
	// Date is the document date. The zero value means the front matter
	// date if there is one, else today.
	Date time.Time
	// Refs supplies references that are not written out in the front matter.
	Refs RefSource
}

// part is one of the "--- name" delimited parts of the source file.
type part struct {
	src []byte
	// firstLine is the line number, in the source file, of the first line.
	firstLine int
}

type document struct {
	frontMatter []byte
	parts       map[string]part
}

var partMarker = regexp.MustCompile(`^---\s*([a-z_]+)\s*$`)

// splitDocument cuts the source into its YAML front matter and the abstract,
// middle and back parts.
func splitDocument(src []byte) (*document, error) {
	// Line endings are normalized first, so that a file saved on Windows
	// does not put carriage returns into code blocks.
	src = bytes.ReplaceAll(src, []byte("\r\n"), []byte("\n"))
	lines := bytes.SplitAfter(src, []byte("\n"))
	if len(lines) > 0 {
		// A byte order mark is not part of the text.
		lines[0] = bytes.TrimPrefix(lines[0], []byte("\uFEFF"))
	}
	if len(lines) == 0 || strings.TrimSpace(string(lines[0])) != "---" {
		return nil, fmt.Errorf("line 1: expected the front matter to start with ---")
	}

	doc := &document{parts: map[string]part{}}
	current := "" // "" is the front matter
	var buf []byte
	start := 2
	flush := func() error {
		if current == "" {
			doc.frontMatter = buf
			return nil
		}
		if _, dup := doc.parts[current]; dup {
			return fmt.Errorf("line %d: part %q appears twice", start-1, current)
		}
		doc.parts[current] = part{src: buf, firstLine: start}
		return nil
	}
	for i, line := range lines[1:] {
		m := partMarker.FindSubmatch(bytes.TrimRight(line, "\r\n"))
		if m == nil {
			buf = append(buf, line...)
			continue
		}
		if err := flush(); err != nil {
			return nil, err
		}
		current, buf, start = string(m[1]), nil, i+3
		switch current {
		case "abstract", "middle", "back":
		default:
			return nil, fmt.Errorf("line %d: unsupported part %q", i+2, current)
		}
	}
	if err := flush(); err != nil {
		return nil, err
	}
	for _, name := range []string{"abstract", "middle"} {
		if _, ok := doc.parts[name]; !ok {
			return nil, fmt.Errorf("missing %q part", "--- "+name)
		}
	}
	return doc, nil
}

// converter holds the state shared between the parts of one document.
type converter struct {
	fm   *frontMatter
	refs *references
	// tagBCP14 is set when the draft asks for the tagged BCP 14 boilerplate.
	// The requirement keywords are then wrapped in <bcp14> everywhere.
	tagBCP14 bool
	anchors  map[string]bool
	xrefs    []xrefUse
	// bracketed are the names written in square brackets in plain text.
	bracketed []xrefUse
}

// xrefUse is a cross-reference waiting to be checked against the anchors and
// references that exist once the whole document has been read.
type xrefUse struct {
	target string
	line   int
}

// Convert turns the Markdown source of a draft into RFCXML v3.
func Convert(src []byte, opts Options) ([]byte, error) {
	doc, err := splitDocument(src)
	if err != nil {
		return nil, err
	}
	fm, err := parseFrontMatter(doc.frontMatter)
	if err != nil {
		return nil, err
	}
	refs, err := newReferences(fm)
	if err != nil {
		return nil, err
	}
	c := &converter{
		fm:       fm,
		refs:     refs,
		tagBCP14: bytes.Contains(src, []byte("{::boilerplate bcp14-tagged}")),
		anchors:  map[string]bool{},
	}

	date := dateOf(time.Now())
	switch {
	case !opts.Date.IsZero():
		date = dateOf(opts.Date)
	case fm.Date != "":
		if date, err = parseDate(fm.Date); err != nil {
			return nil, fmt.Errorf("front matter: %v", err)
		}
	}

	out := &xmlBuf{}
	out.line(`<?xml version="1.0" encoding="UTF-8"?>`)
	out.line("<!-- generated by mkd2xml; edit the Markdown source instead -->")
	out.open(c.rfcElement())

	out.open("<front>")
	c.renderFrontMatter(out, date)
	out.open("<abstract>")
	if err := c.renderFlow(doc.parts["abstract"], out); err != nil {
		return nil, err
	}
	out.close("</abstract>")
	c.renderVenue(out)
	out.close("</front>")

	out.open("<middle>")
	if err := c.renderSections(doc.parts["middle"], out); err != nil {
		return nil, err
	}
	out.close("</middle>")

	// The back sections are rendered before the references so that their
	// citations are counted, but they are placed after them.
	backSections := &xmlBuf{depth: out.depth + 1}
	if back, ok := doc.parts["back"]; ok {
		if err := c.renderSections(back, backSections); err != nil {
			return nil, err
		}
	}
	out.open("<back>")
	if err := refs.render(out, opts.Refs); err != nil {
		return nil, err
	}
	out.raw(backSections.String())
	out.close("</back>")

	out.close("</rfc>")

	for _, x := range c.xrefs {
		if !c.anchors[x.target] && !refs.known[x.target] {
			return nil, fmt.Errorf("line %d: {{%s}} refers to nothing: it is neither a section anchor nor a reference (use {{!%s}} or {{?%s}} to cite and fetch a reference)", x.line, x.target, x.target, x.target)
		}
	}
	for _, b := range c.bracketed {
		if refs.known[b.target] {
			return nil, fmt.Errorf("line %d: [%s] would be read by kramdown-rfc as a citation of that reference; write {{%s}}, or \\[%s\\] for the text itself", b.line, b.target, b.target, b.target)
		}
	}
	return []byte(out.String()), nil
}

func (c *converter) rfcElement() string {
	fm := c.fm
	attrs := []string{
		`version="3"`,
		`ipr="` + escAttr(fm.IPR) + `"`,
		`docName="` + escAttr(fm.Docname) + `"`,
		`category="` + escAttr(fm.Category) + `"`,
	}
	// As in kramdown-rfc, standards track and BCP documents carry consensus
	// unless they say otherwise, other categories only when they ask, and
	// the absence of consensus is expressed by leaving the attribute out.
	consensus := fm.Category == "std" || fm.Category == "bcp"
	if fm.Consensus != nil {
		consensus = *fm.Consensus
	}
	if consensus {
		attrs = append(attrs, `consensus="true"`)
	}
	if fm.SubmissionType != "" {
		attrs = append(attrs, `submissionType="`+escAttr(fm.SubmissionType)+`"`)
	}
	if fm.Obsoletes != "" {
		attrs = append(attrs, `obsoletes="`+escAttr(fm.Obsoletes)+`"`)
	}
	if fm.Updates != "" {
		attrs = append(attrs, `updates="`+escAttr(fm.Updates)+`"`)
	}
	attrs = append(attrs, `tocInclude="true"`, `sortRefs="true"`, `symRefs="true"`)
	return "<rfc " + strings.Join(attrs, " ") + ">"
}

func (c *converter) renderFrontMatter(out *xmlBuf, date xmlDate) {
	fm := c.fm
	title := "<title"
	if fm.Abbrev != "" {
		title += ` abbrev="` + escAttr(fm.Abbrev) + `"`
	}
	out.line(title + ">" + escText(fm.Title) + "</title>")
	out.line(`<seriesInfo name="Internet-Draft" value="` + escAttr(fm.Docname) + `"/>`)

	for _, a := range fm.Author {
		tag := "<author"
		if a.Initials != "" {
			tag += ` initials="` + escAttr(a.Initials) + `"`
		}
		if a.Surname != "" {
			tag += ` surname="` + escAttr(a.Surname) + `"`
		}
		if a.Fullname != "" {
			tag += ` fullname="` + escAttr(a.Fullname) + `"`
		}
		// The organization and address are written even when empty, as
		// kramdown-rfc writes them.
		out.open(tag + ">")
		out.line("<organization>" + escText(a.Organization) + "</organization>")
		out.open("<address>")
		if a.Email != "" {
			out.line("<email>" + escText(a.Email) + "</email>")
		}
		out.close("</address>")
		out.close("</author>")
	}

	out.line(dateElement(date))
	if fm.Area != "" {
		out.line("<area>" + escText(fm.Area) + "</area>")
	}
	if fm.Workgroup != "" {
		out.line("<workgroup>" + escText(fm.Workgroup) + "</workgroup>")
	}
	for _, k := range fm.Keyword {
		out.line("<keyword>" + escText(k) + "</keyword>")
	}
}

// renderVenue writes the "About This Document" note, with the same wording
// kramdown-rfc generates from the venue block.
func (c *converter) renderVenue(out *xmlBuf) {
	v := c.fm.Venue
	if v == nil {
		return
	}
	eref := func(target string) string {
		return `<eref target="` + escAttr(target) + `"/>`
	}

	out.open(`<note removeInRFC="true">`)
	out.line("<name>About This Document</name>")

	if base := baseDocname(c.fm.Docname); base != "" {
		out.open("<t>")
		if v.Latest != "" {
			out.line("The latest revision of this draft can be found at " + eref(v.Latest) + ".")
		}
		out.line("Status information for this document may be found at " +
			eref("https://datatracker.ietf.org/doc/"+base+"/") + ".")
		out.close("</t>")
	}

	if local, host, ok := strings.Cut(v.Mail, "@"); ok {
		// Lists hosted by the IETF family have well-known archive and
		// subscription pages.
		ietfHosted := host == "ietf.org" || host == "irtf.org" || host == "iab.org"
		group, groupType, arch := v.Group, v.Type, v.Arch
		if group == "" {
			group = local
		}
		if groupType == "" {
			switch {
			case strings.HasPrefix(host, "ietf."):
				groupType = "Working Group"
			case strings.HasPrefix(host, "irtf."):
				groupType = "Research Group"
			default:
				groupType = "Group"
			}
		}
		if arch == "" && ietfHosted {
			arch = "https://mailarchive.ietf.org/arch/browse/" + local + "/"
		}

		out.open("<t>")
		list := "Discussion of this document takes place on the " + escText(group+" "+groupType) +
			" mailing list (" + eref("mailto:"+v.Mail) + ")"
		if arch != "" {
			list += ", which is archived at " + eref(arch)
		}
		out.line(list + ".")
		if ietfHosted {
			out.line("Subscribe at " + eref("https://www.ietf.org/mailman/listinfo/"+local+"/") + ".")
		}
		out.close("</t>")
	}

	if v.GitHub != "" {
		out.open("<t>")
		out.line("Source for this draft and an issue tracker can be found at " +
			eref("https://github.com/"+v.GitHub) + ".")
		out.close("</t>")
	}
	out.close("</note>")
}
